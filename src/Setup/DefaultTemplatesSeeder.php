 *  - A system row is REFRESHED — JSON, schema version, name, category,
 *    description and sort order — when the shipped file changed AND the
 *    row still holds exactly what the plugin seeded, i.e. the admin
 *    never edited its design. The canonical hash of what was seeded is
 *    remembered per slug in the `imgsig_template_hashes` option; rows
