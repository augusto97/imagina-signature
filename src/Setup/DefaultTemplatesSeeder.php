	/**
	 * Swaps a seeded system template's English name / description for
	 * the current locale's translation.
	 *
	 * Only fields still holding the seeded source text are touched: an
	 * admin who renamed a system template keeps their wording, and
	 * user-created templates are never translated.
	 *
	 * @since 1.1.0
	 *
	 * @param array<string, mixed> $template Serialised template ({@see \ImaginaSignatures\Models\Template::to_array()}).
	 *
	 * @return array<string, mixed>
	 */
	public static function localize( array $template ): array {
		$slug = isset( $template['slug'] ) ? (string) $template['slug'] : '';
		if ( empty( $template['is_system'] ) || ! isset( self::META[ $slug ] ) ) {
			return $template;
		}

		$translated = self::translated_meta()[ $slug ] ?? null;
		if ( null === $translated ) {
			return $template;
		}

		foreach ( [ 'name', 'description' ] as $field ) {
			if ( isset( $template[ $field ] ) && self::META[ $slug ][ $field ] === $template[ $field ] ) {
				$template[ $field ] = $translated[ $field ];
			}
		}
		return $template;
	}

	/**
	 * Inverse of {@see self::localize()} for writes: when an admin saves
	 * a system template's metadata form without changing the (translated)
	 * name / description it was shown, store the English source again so
	 * other locales keep seeing their own translation.
	 *
	 * @since 1.1.0
	 *
	 * @param string               $slug    Slug of the template being updated.
	 * @param bool                 $is_system Whether it's a seeded system row.
	 * @param array<string, mixed> $payload Incoming update payload.
	 *
	 * @return array<string, mixed>
	 */
	public static function delocalize( string $slug, bool $is_system, array $payload ): array {
		if ( ! $is_system || ! isset( self::META[ $slug ] ) ) {
			return $payload;
		}

		$translated = self::translated_meta()[ $slug ] ?? null;
		if ( null === $translated ) {
			return $payload;
		}

		foreach ( [ 'name', 'description' ] as $field ) {
			if ( isset( $payload[ $field ] ) && is_string( $payload[ $field ] ) && trim( $payload[ $field ] ) === $translated[ $field ] ) {
				$payload[ $field ] = self::META[ $slug ][ $field ];
			}
		}
		return $payload;
	}

	/**
	 * English source metadata of the seeded templates (slug => meta).
	 *
	 * @since 1.1.0
	 *
	 * @return array<string, array{name: string, category: string, sort_order: int, description: string}>
	 */
	public static function source_meta(): array {
		return self::META;
	}

	/**
	 * Canonical hash of a template JSON document: SHA-256 of its
	 * re-encoded form, so formatting (pretty-printing, the DB's encoding)
	 * never counts as an edit. Undecodable input hashes as-is.
	 *
	 * @since 1.2.0
	 *
	 * @param string $json Template JSON.
	 *
	 * @return string
	 */
	public static function hash_json( string $json ): string {
		$decoded = json_decode( $json, true );
		$encoded = is_array( $decoded ) ? (string) wp_json_encode( $decoded ) : $json;
		return hash( 'sha256', $encoded );
	}

	/**
	 * @var TemplateRepository
	 */
	private TemplateRepository $repo;

	/**
	 * Folder holding `<slug>.json`; null = the plugin's `templates/`.
	 *
	 * @var string|null
	 */
	private ?string $templates_dir;

	/**
	 * @param TemplateRepository $repo          Repository.
	 * @param string|null        $templates_dir Folder of the template files (tests); defaults to `templates/`.
	 */
	public function __construct( TemplateRepository $repo, ?string $templates_dir = null ) {
		$this->repo          = $repo;
		$this->templates_dir = $templates_dir;
	}

	/**
	 * Inserts missing templates and refreshes unmodified system rows
	 * whose shipped file changed.
	 *
	 * @since 1.0.0
	 * @since 1.2.0 Refreshes unmodified system rows; records seeded hashes.
	 *
	 * @return void
	 */
	public function seed(): void {
		$base_dir = $this->templates_dir ?? trailingslashit( IMGSIG_PATH ) . 'templates';
		if ( ! is_dir( $base_dir ) ) {
			return;
		}

		$stored_hashes = get_option( self::HASH_OPTION, [] );
		$hashes        = is_array( $stored_hashes ) ? $stored_hashes : [];
		$changed       = false;

		foreach ( self::META as $slug => $meta ) {
			$file = rtrim( $base_dir, '/\\' ) . '/' . $slug . '.json';
			if ( ! is_file( $file ) ) {
				continue;
			}

			$decoded = json_decode( (string) file_get_contents( $file ), true ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
			if ( ! is_array( $decoded ) ) {
				continue;
			}

			$json = (string) wp_json_encode( $decoded );
			$hash = self::hash_json( $json );
			$row  = [
				'name'           => $meta['name'],
				'category'       => $meta['category'],
				'description'    => $meta['description'],
				'json_content'   => $json,
				'sort_order'     => $meta['sort_order'],
				'schema_version' => isset( $decoded['schema_version'] ) ? (string) $decoded['schema_version'] : '1.0',
			];

			$existing = $this->repo->find_by_slug( $slug );

			if ( null === $existing ) {
				$this->repo->insert(
					array_merge(
						$row,
						[
							'slug'      => $slug,
							'is_system' => true,
						]
					)
				);
				$hashes[ $slug ] = $hash;
				$changed         = true;
				continue;
			}

			if ( ! $existing->is_system ) {
				continue;
			}

			$current = self::hash_json( $existing->json_content );
			if ( hash_equals( $hash, $current ) ) {
				// Already the shipped version — remember it as seeded.
				if ( ( $hashes[ $slug ] ?? '' ) !== $hash ) {
					$hashes[ $slug ] = $hash;
					$changed         = true;
				}
				continue;
			}

			if ( ! $this->is_pristine( $slug, $current, $hashes ) ) {
				continue; // The admin edited it: keep their version.
			}

			$this->repo->update( $existing->id, $row );
			$hashes[ $slug ] = $hash;
			$changed         = true;
		}

		if ( $changed ) {
			update_option( self::HASH_OPTION, $hashes, false );
		}
	}

	/**
	 * Whether a system row still holds exactly what the plugin seeded.
	 *
	 * @param string                $slug    Template slug.
	 * @param string                $current Canonical hash of the row's JSON.
	 * @param array<string, string> $hashes  Recorded seeded hashes.
	 *
	 * @return bool
	 */
	private function is_pristine( string $slug, string $current, array $hashes ): bool {
		if ( isset( $hashes[ $slug ] ) && is_string( $hashes[ $slug ] ) ) {
			return hash_equals( $hashes[ $slug ], $current );
		}
		return in_array( $current, self::LEGACY_HASHES[ $slug ] ?? [], true );
	}
