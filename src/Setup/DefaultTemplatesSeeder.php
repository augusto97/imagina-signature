 *    hashes of the files those versions shipped ({@see self::LEGACY_HASHES}).
 *  - Edited system rows and admin-created rows are never touched.
 *
 * Idempotent: runs on activation and on every in-place upgrade
 * ({@see \ImaginaSignatures\Core\Installer::install()}); a run with
 * nothing to do performs no writes.
 *
 * Template files may use any supported schema version (1.0 or 1.1,
 * see {@see \ImaginaSignatures\Services\JsonSchemaValidator::SUPPORTED_VERSIONS});
 * the row's `schema_version` column records the file's version and
 * defaults to 1.0 for files that predate the field. The shipped files
 * are generated by `scripts/templates/build-templates.mjs`.
 *
 * @since 1.0.0
 * @since 1.2.0 Refreshes unmodified system templates on upgrade.
