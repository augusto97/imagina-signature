/**
 * Shared catalogue plumbing for the i18n scripts: runs both
 * extractors, merges them into one .pot, and compiles .po files into
 * the runtime artefacts (.mo for PHP, .json for the React apps).
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractJs } from '../extract-js.mjs';
import {
  compileMo,
  createEntry,
  entryKey,
  isTranslated,
  parseHeader,
  parsePo,
  renderHeader,
  serializePo,
} from './po.mjs';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
export const DOMAIN = 'imagina-signatures';
export const LANG_DIR = join(ROOT, 'languages');
export const POT_PATH = join(LANG_DIR, `${DOMAIN}.pot`);

/** Plugin version from the main plugin file header. */
export function pluginVersion() {
  const php = readFileSync(join(ROOT, 'imagina-signatures.php'), 'utf8');
  const m = /^\s*\*\s*Version:\s*(\S+)/m.exec(php);
  return m ? m[1] : '0.0.0';
}

/** Runs the PHP tokenizer extractor. Requires the `php` CLI. */
export function extractPhp() {
  let out;
  try {
    out = execFileSync('php', [join(ROOT, 'scripts/i18n/extract-php.php')], {
      cwd: ROOT,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    });
  } catch (err) {
    throw new Error(
      `PHP extraction failed — is the php CLI installed and on PATH?\n${err.message}`,
    );
  }
  return JSON.parse(out);
}

/**
 * Extracts PHP + JS strings into a deduplicated list of .pot entries,
 * ordered by first reference (PHP first, then JS — both by path/line).
 *
 * @returns {{ entries: object[], phpDynamic: object[], jsDynamic: object[] }}
 */
export function buildTemplateEntries() {
  const php = extractPhp();
  const js = extractJs(ROOT);
  const map = new Map();

  const add = ({ msgid, msgctxt = null, msgidPlural = null, references, notes }) => {
    const key = entryKey({ msgid, msgctxt });
    let entry = map.get(key);
    if (!entry) {
      entry = createEntry({
        msgid,
        msgctxt,
        msgidPlural,
        msgstr: msgidPlural !== null ? ['', ''] : [''],
      });
      map.set(key, entry);
    }
    if (msgidPlural !== null && entry.msgidPlural === null) {
      entry.msgidPlural = msgidPlural;
      entry.msgstr = ['', ''];
    }
    for (const ref of references) if (!entry.references.includes(ref)) entry.references.push(ref);
    for (const note of notes) if (note && !entry.extracted.includes(note)) entry.extracted.push(note);
  };

  for (const e of php.entries) {
    add({
      msgid: e.msgid,
      msgctxt: e.msgctxt ?? null,
      msgidPlural: e.msgidPlural ?? null,
      references: [e.reference],
      notes: e.note ? [e.note] : [],
    });
  }
  for (const e of js.entries.values()) {
    add({ msgid: e.msgid, references: e.references, notes: e.notes });
  }

  // Flag sprintf placeholders so translation tools validate them.
  for (const entry of map.values()) {
    const text = `${entry.msgid}${entry.msgidPlural ?? ''}`;
    if (/%(\d+\$)?[sd]/.test(text)) {
      const isPhp = entry.references.some((r) => !r.startsWith('assets/'));
      entry.flags = [isPhp ? 'php-format' : 'javascript-format'];
    }
  }

  return { entries: [...map.values()], phpDynamic: php.dynamic, jsDynamic: js.dynamic };
}

export function potHeader() {
  const header = new Map([
    ['Project-Id-Version', `Imagina Signatures ${pluginVersion()}`],
    ['Report-Msgid-Bugs-To', 'https://github.com/augusto97/imagina-signature/issues'],
    ['Last-Translator', ''],
    ['Language-Team', ''],
    ['MIME-Version', '1.0'],
    ['Content-Type', 'text/plain; charset=UTF-8'],
    ['Content-Transfer-Encoding', '8bit'],
    ['Plural-Forms', 'nplurals=INTEGER; plural=EXPRESSION;'],
    ['X-Generator', 'scripts/i18n/make-pot.mjs'],
    ['X-Domain', DOMAIN],
  ]);
  return renderHeader(header);
}

export const POT_COMMENTS = [
  'Copyright (C) 2026 Imagina WP',
  'This file is distributed under the GPL-2.0-or-later license.',
  'Generated by `npm run i18n:pot` — do not edit by hand.',
];

export function renderPot(entries) {
  return serializePo({ header: potHeader(), headerComments: POT_COMMENTS, entries });
}

/** Lists `languages/*.po` as `{ locale, path }`. */
export function listPoFiles() {
  if (!existsSync(LANG_DIR)) return [];
  return readdirSync(LANG_DIR)
    .filter((f) => f.startsWith(`${DOMAIN}-`) && f.endsWith('.po'))
    .sort()
    .map((f) => ({ locale: f.slice(DOMAIN.length + 1, -3), path: join(LANG_DIR, f) }));
}

export function readCatalogue(path) {
  return parsePo(readFileSync(path, 'utf8'));
}

/** True when the entry is referenced from the React sources. */
export function usedByJs(entry) {
  return entry.references.some((r) => r.startsWith('assets/'));
}

/**
 * Runtime artefacts for one .po catalogue.
 *
 * JSON holds only the strings referenced from JS (the React `__()`
 * has no context / plural support), one entry per line so diffs stay
 * readable. Keys are sorted for deterministic output.
 *
 * @returns {{ mo: Buffer, json: string, translated: number, total: number }}
 */
export function compileCatalogue(catalogue) {
  const live = catalogue.entries.filter((e) => !e.obsolete);
  const mo = compileMo(catalogue.header, live);

  const jsPairs = live
    .filter((e) => usedByJs(e) && e.msgctxt === null && e.msgidPlural === null && isTranslated(e))
    .map((e) => [e.msgid, e.msgstr[0]])
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const json =
    jsPairs.length === 0
      ? '{}\n'
      : `{\n${jsPairs.map(([k, v]) => `${JSON.stringify(k)}:${JSON.stringify(v)}`).join(',\n')}\n}\n`;

  return {
    mo,
    json,
    jsCount: jsPairs.length,
    translated: live.filter(isTranslated).length,
    total: live.length,
  };
}

export function moPath(locale) {
  return join(LANG_DIR, `${DOMAIN}-${locale}.mo`);
}

export function jsonPath(locale) {
  return join(LANG_DIR, `${DOMAIN}-${locale}.json`);
}

export { parseHeader, renderHeader, entryKey, isTranslated, serializePo, parsePo, createEntry };
